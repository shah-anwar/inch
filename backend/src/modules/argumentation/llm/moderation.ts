import { z } from "zod";
import { callMistral } from "./mistral.js";

const SYSTEM_MODERATION =
  "You are a precise content moderator for structured argumentation scheme variables. Obey the JSON output contract exactly.";

/** LLM JSON shape for variable-input moderation (withContext strategy). */
const ModerationLlmResponseSchema = z.object({
  passed: z.boolean(),
  violations: z.array(
    z.object({
      variableId: z.string(),
      reason: z.string(),
    }),
  ),
});

export type ModerationResult =
  | { passed: true }
  | {
      passed: false;
      violations: Array<{
        variableId: string;
        reason: string;
      }>;
    };

/** Thrown when variable inputs fail moderation before text generation. */
export class ModerationFailedError extends Error {
  readonly violations: Array<{ variableId: string; reason: string }>;

  constructor(violations: Array<{ variableId: string; reason: string }>) {
    super("moderation_failed");
    this.name = "ModerationFailedError";
    this.violations = violations;
  }
}

function buildWithContextUserMessage(params: {
  schemeId: string;
  schemeName: string;
  conclusionTemplate: string;
  variables: Array<{ variableId: string; label: string; value: string }>;
}): string {
  const lines = params.variables.map(
    (v) => `- ${v.label} (variableId: ${v.variableId}): ${v.value}`,
  );
  return [
    `Scheme: ${params.schemeName} (id: ${params.schemeId})`,
    `Conclusion template: ${params.conclusionTemplate}`,
    "",
    "Variable values:",
    lines.join("\n"),
    "",
    "Decide whether these values coherently and appropriately fill the scheme given the conclusion template.",
    "Return only a single JSON object with this exact shape (no markdown fences, no commentary before or after):",
    '{"passed":boolean,"violations":[{"variableId":string,"reason":string}]}',
    "If passed is true, violations must be []. If passed is false, list each offending variableId with a short reason.",
  ].join("\n");
}

/**
 * Moderates raw scheme variable values before any text is generated, using the
 * `withContext` prompt chosen in experiments/results/moderation/FINDINGS.md.
 *
 * Fails open on API, parse or validation errors: the gate must not block users
 * when the model is unavailable or returns unusable output. Structural checks
 * (scheme, variables, CQ response rules) still run regardless, and failures are
 * logged server-side. A model reply of passed:false that names no real variable
 * is also treated as a pass, because there is nothing to show the user.
 */
export async function moderateVariableInputs(params: {
  schemeId: string;
  schemeName: string;
  conclusionTemplate: string;
  variables: Array<{ variableId: string; label: string; value: string }>;
}): Promise<ModerationResult> {
  const validIds = new Set(params.variables.map((v) => v.variableId));

  let raw: string | null;
  try {
    raw = await callMistral(
      [
        { role: "system", content: SYSTEM_MODERATION },
        { role: "user", content: buildWithContextUserMessage(params) },
      ],
      {
        temperature: 0.1,
        maxTokens: 256,
        responseFormat: "json_object",
      },
    );
  } catch (e) {
    console.error("[moderation] Mistral call failed:", e);
    return { passed: true };
  }

  if (raw == null || raw === "") {
    console.error("[moderation] Mistral returned no content (missing API key or request failed)");
    return { passed: true };
  }

  let parsedJson: unknown;
  try {
    parsedJson = JSON.parse(raw);
  } catch (e) {
    console.error("[moderation] JSON parse failed:", e, "raw:", raw);
    return { passed: true };
  }

  const parsed = ModerationLlmResponseSchema.safeParse(parsedJson);
  if (!parsed.success) {
    console.error("[moderation] Response validation failed:", parsed.error.format(), "raw:", raw);
    return { passed: true };
  }

  const data = parsed.data;
  if (data.passed) {
    return { passed: true };
  }

  const violations = data.violations
    .filter((v) => validIds.has(v.variableId))
    .map((v) => ({ variableId: v.variableId, reason: v.reason }));

  if (violations.length === 0) {
    console.error(
      "[moderation] Model returned passed:false but no valid variableIds in violations after filtering; failing open. raw:",
      raw,
    );
    return { passed: true };
  }

  return { passed: false, violations };
}

/**
 * Result of the submission-time text hook. The hook currently allows everything:
 * the chosen text was generated by the server from inputs that already passed
 * `moderateVariableInputs`.
 */
export interface ArgumentTextModerationResult {
  allowed: boolean;
  reason: string | null;
}

/**
 * Moderation hook for final argument text at submission (separate from variable gate).
 *
 * @param _text Candidate argument text.
 * @returns Moderation decision and optional rejection reason.
 */
export async function moderateArgumentSubmission(
  _text: string,
): Promise<ArgumentTextModerationResult> {
  void _text;
  return {
    allowed: true,
    reason: null,
  };
}
